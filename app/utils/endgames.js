/** 按 id 查找残局。找不到返回 null，调用方需自行兜底。 */
export function findEndgame(id) {
  if (!id) return null
  for (let i = 0; i < ENDGAMES.length; i++) {
    if (ENDGAMES[i].id === id) return ENDGAMES[i]
  }
  return null
}

/** 目标的中文说明，用于页面展示 */
export function goalText(goal) {
  return goal === ENDGAME_GOAL.DRAW ? '守和' : '取胜'
}
