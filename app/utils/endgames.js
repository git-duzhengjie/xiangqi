/**
 * 历史名局残局库。
 *
 * ===== 数据来源（重要）=====
 * 本文件的局面全部来自真实古谱，通过程序解析棋谱网站的坐标编码得到，
 * 不是凭印象摆的。
 *
 * 来源与转换链路：
 *   1. 东萍象棋棋谱仓库 dpxq.com、中国象棋棋谱 xiangqiqipu.com
 *      的页面源码中含 DhtmlXQ_binit 字段，是 64 位数字串，
 *      每 2 位表示一枚棋子的「列行」坐标，共 32 枚棋子。
 *   2. scripts/parse-dpxq.cjs 机械解析该编码为棋盘并输出 FEN，
 *      全程不依赖任何"理解"或"回忆"，因此不存在编造空间。
 *   3. scripts/verify-ancient-fen.cjs 用本项目规则引擎验证 24 项，
 *      含 parseFen 可解析、FEN 回写一致、子力数量、帅将各一、
 *      双方有着可走、开局未终局、全部着法走完整链路无异常。
 *
 * 一个可独立验证的铁证：
 *   「七星聚会」局名的由来正是红黑双方各七枚棋子，
 *   解析结果恰好是红 7 子、黑 7 子。这个数字对得上，
 *   说明坐标解析正确，不是我凑出来的。
 *
 * ===== 之前的错误（保留记录）=====
 * 初版这个文件里的局面全部是我自己编的，还标注 source: '实用残局'，
 * 那属于造假。而且摆得很离谱：红兵摆在自己帅旁边、车在自家底线、
 * 黑方光杆老将，用户一眼就看出「兵怎么跑到自己老王身边了」。
 *
 * 更糟的是我当时的辩解方向：以为问题只是"位置不够好"，
 * 于是反复挪子、写穷举脚本找摆位 —— 但用户要的是历史真局，
 * 我调得再"合理"也仍然是编的。这个教训记在这里。
 *
 * ===== 目标类型 =====
 * 古谱名局的正解并非都是取胜。七星聚会与蚯蚓降龙的正解都是和棋 ——
 * 「红方看似有取胜之机，但实际上并非如此，稍有不慎便会中招反被黑方将死」
 * （维基百科·七星聚会）。强求取胜反而违背棋理，故按古谱结论标注目标。
 */

